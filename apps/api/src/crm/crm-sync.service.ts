import { Injectable, Logger, OnModuleInit, OnModuleDestroy } from '@nestjs/common';
import { InjectRepository } from '@nestjs/typeorm';
import { MoreThan, Repository } from 'typeorm';
import { NazrRequestEntity } from '../modules/nazr-requests/entities/nazr-request.entity';
import { PaymentEntity } from '../modules/payments/entities/payment.entity';
import { UserEntity } from '../modules/auth/entities/user.entity';
import { CrmConfigService } from './crm.config';
import { Crm24ClientService } from './crm24-client.service';

interface CrmPayment {
  id: string;
  tracking_code: string;
  paymentsstatus: string;
  amount_currency_value: string;
  cf_1764: string;
  relatedcontact: string;
  assigned_user_id: string;
}

const CRM_PAYMENT_FIELDS = 'id,tracking_code,paymentsstatus,amount_currency_value,cf_1764,relatedcontact,assigned_user_id';
const PAID = 'پرداخت شده';
const PENDING = 'در انتظار پرداخت';
const CANCELLED = 'لغو شده';

interface ContactIdentity {
  donorMobile: string;
  donorFullName: string;
  donorFirstName?: string | null;
  donorLastName?: string | null;
  donorGender?: 'male' | 'female' | null;
}

interface CrmContact {
  id: string;
  mobile: string;
  firstname: string;
  lastname: string;
  cf_1756: string;
  assigned_user_id: string;
}

class ReviewRequired extends Error {}

// All codes generated by Nazr (including the older timestamp format).
function codeLiteral(code: string): string {
  if (!/^NE-[A-Z0-9-]{1,37}$/.test(code)) throw new Error('کد پیگیری نامعتبر');
  return `'${code}'`;
}

interface CrmIdResponse {
  id: string;
}

/** نگاشت slug طرح به مقدار picklist «نیت پرداخت نذر» در CRM. */
const PLAN_INTENT_BY_SLUG: Record<string, string> = {
  international: 'بین الملل',
  'nazr-royesh': 'رویش',
  'niaz-rooz': 'نیاز روز',
};

/** نام سرویس CRM و کد حسابداری آن (طبق مشخصات: نذر امام با کد 1111). */
const NAZR_SERVICE_NAME = 'نذر امام';
const NAZR_SERVICE_CODE = '1111';

/**
 * همگام‌سازی نذر امام با CRM24 (vtiger) — مستقیم، بدون عبور از سپیدار.
 *
 * نگاشت مخاطب (Contacts): نام، نام خانوادگی، شماره تماس، جنسیت،
 * منبع سرنخ «سایت نذر امام»، «مرتبط با نذر امام: بله».
 *
 * نگاشت پرداخت (Payments): سرویس «نذر امام» (کد حسابداری 1111)، مبلغ،
 * وضعیت (در انتظار پرداخت ← پس از پرداخت: پرداخت شده)، حالت (پرداخت آنلاین/
 * کارت به کارت)، ارجاع به کاربر CRM، نوع پرداخت «نذر امام»، نیت پرداخت
 * (بین الملل/رویش/نیاز روز)، توضیحات = یادداشت اختیاری سایت.
 *
 * همه خطاها فقط لاگ می‌شوند — جریان نذر هرگز به‌خاطر CRM نمی‌شکند.
 */
@Injectable()
export class CrmSyncService implements OnModuleInit, OnModuleDestroy {
  private timer?: ReturnType<typeof setTimeout>;
  private stopped = false;
  private retryNeeded = false;
  private readonly contactLookups = new Map<string, Promise<string>>();


  onModuleInit(): void {
    if (this.crmConfig.enabled) this.scheduleReconciliation(60_000);
  }

  onModuleDestroy(): void {
    this.stopped = true;
    clearTimeout(this.timer);
  }

  private scheduleReconciliation(delay: number): void {
    this.timer = setTimeout(async () => {
      try {
        this.retryNeeded = false;
        // A failure in one collection must not starve the other collections.
        for (const reconcile of [this.reconcilePaid, this.reconcileRequests, this.reconcileUsers]) {
          if (this.stopped) break;
          try { await reconcile.call(this); }
          catch (error) { this.failure('reconcile collection', error); }
        }
        this.logger.log('CRM reconciliation completed');
      } catch (error) {
        this.logger.error(`CRM reconcile: ${this.errMessage(error)}`);
      } finally {
        if (!this.stopped) this.scheduleReconciliation(this.retryNeeded ? 5 * 60_000 : 60 * 60_000);
      }
    }, delay);
    this.timer.unref();
  }

  // Scan committed payments using a stable key. CRM24 returns at most 100 rows.
  private async reconcilePaid(): Promise<void> {
    let cursor = '';
    let scanned = 0;
    while (!this.stopped) {
      const page = await this.paymentsRepo.find({
        where: { status: 'paid', id: MoreThan(cursor) },
        relations: { nazrRequest: true },
        order: { id: 'ASC' }, take: 40,
      });
      if (!page.length) { this.logger.log(`CRM paid scan complete: ${scanned}`); return; }
      try {
        const codes = page.map(p => codeLiteral(p.nazrRequest.trackingCode)).join(',');
        const remote = await this.client.query<CrmPayment>(
          `SELECT ${CRM_PAYMENT_FIELDS} FROM Payments WHERE tracking_code IN (${codes}) LIMIT 100;`,
        );
        for (const payment of page) {
          if (this.stopped) return;
          if (this.held(payment.nazrRequest.trackingCode)) continue;
          try {
            const matches = remote.filter(r => r.tracking_code === payment.nazrRequest.trackingCode);
            if (matches.length === 1 && this.matchesPaid(matches[0], payment)) continue;
            await this.syncByPaymentId(payment.id);
          } catch (error) { this.failure(`reconcile payment ${payment.id}`, error); }
        }
      } catch (error) { this.failure('reconcile payments page', error); }
      cursor = page[page.length - 1].id;
      scanned += page.length;
    }
  }

  private async reconcileRequests(): Promise<void> {
    let cursor = '';
    let scanned = 0;
    while (!this.stopped) {
      const page = await this.nazrRequestsRepo.find({
        where: { id: MoreThan(cursor) }, order: { id: 'ASC' }, take: 40,
      });
      if (!page.length) { this.logger.log(`CRM requests scan complete: ${scanned}`); return; }
      try {
        const codes = page.map(r => codeLiteral(r.trackingCode)).join(',');
        const remote = await this.client.query<CrmPayment>(
          `SELECT ${CRM_PAYMENT_FIELDS} FROM Payments WHERE tracking_code IN (${codes}) LIMIT 100;`,
        );
        for (const request of page) {
          if (this.stopped) return;
          if (this.held(request.trackingCode)) continue;
          const matches = remote.filter(r => r.tracking_code === request.trackingCode);
          if (matches.length === 1 && matches[0].cf_1764 === NAZR_SERVICE_NAME &&
            (matches[0].paymentsstatus === PAID ||
              (matches[0].paymentsstatus === this.unpaidStatus(request) &&
                Number(matches[0].amount_currency_value) === this.rialAmount(request.amount)))) continue;
          await this.syncNewNazr(request.id);
        }
      } catch (error) { this.failure('reconcile requests page', error); }
      cursor = page[page.length - 1].id;
      scanned += page.length;
      if (scanned % 200 === 0) this.logger.log(`CRM requests scanned: ${scanned}`);
    }
  }

  private async reconcileUsers(): Promise<void> {
    let cursor = '';
    let scanned = 0;
    while (!this.stopped) {
      const page = await this.usersRepo.find({
        where: { role: 'donor', id: MoreThan(cursor) },
        select: { id: true, mobile: true, fullName: true, role: true },
        order: { id: 'ASC' }, take: 40,
      });
      if (!page.length) { this.logger.log(`CRM users scan complete: ${scanned}`); return; }
      try {
        const identities = page.map(u => this.userIdentity(u));
        const rows = await this.lookupContacts(identities);
        for (const user of page) {
          if (this.stopped) return;
          try {
            const contact = rows.length < 100 ? this.selectContact(this.userIdentity(user), rows) : undefined;
            if (contact?.cf_1756 === 'بله') continue;
            await this.syncUser(user.id);
          } catch (error) { this.failure(`reconcile user ${user.id}`, error); }
        }
      } catch (error) { this.failure('reconcile users page', error); }
      cursor = page[page.length - 1].id;
      scanned += page.length;
      if (scanned % 200 === 0) this.logger.log(`CRM users scanned: ${scanned}`);
    }
  }

  async syncUser(userId: string): Promise<void> {
    if (!this.crmConfig.enabled) return;
    try {
      const user = await this.usersRepo.findOne({
        where: { id: userId, role: 'donor' },
        select: { id: true, fullName: true, mobile: true, role: true },
      });
      if (!user) return;
      await this.withNazrLock(userId, async () => { await this.upsertContact(this.userIdentity(user)); });
    } catch (error) { this.failure(`syncUser ${userId}`, error); }
  }

  private userIdentity(user: UserEntity): ContactIdentity {
    return { donorMobile: user.mobile, donorFullName: user.fullName };
  }

  private held(code: string): boolean {
    return this.crmConfig.config?.reviewTrackingCodes?.includes(code) ?? false;
  }

  private unpaidStatus(request: NazrRequestEntity): string {
    return ['cancelled', 'rejected'].includes(request.status) ? CANCELLED : PENDING;
  }

  private matchesPaid(remote: CrmPayment, payment: PaymentEntity): boolean {
    return remote.cf_1764 === NAZR_SERVICE_NAME && remote.paymentsstatus === PAID &&
      Number(remote.amount_currency_value) === this.rialAmount(payment.amount);
  }

  // Serialize lookup + write across the callback, periodic sweep and app replicas.
  private async withNazrLock(_id: string, fn: () => Promise<void>): Promise<void> {
    const runner = this.paymentsRepo.manager.connection.createQueryRunner();
    // One shared lock also prevents two different requests/users creating the
    // same CRM contact. No repository calls are made inside the locked write.
    const name = 'nazr-crm-sync-v2';
    await runner.connect();
    try {
      const result: { locked: number }[] = await runner.query('SELECT GET_LOCK(?, 3) AS locked', [name]);
      if (Number(result[0]?.locked) !== 1) throw new Error('قفل همگام‌سازی در دسترس نبود');
      try { await fn(); } finally { await runner.query('SELECT RELEASE_LOCK(?)', [name]); }
    } finally {
      await runner.release();
    }
  }

  private lookup(code: string): Promise<CrmPayment[]> {
    return this.client.query<CrmPayment>(
      `SELECT ${CRM_PAYMENT_FIELDS} FROM Payments WHERE tracking_code=${codeLiteral(code)} LIMIT 2;`,
    );
  }

  private readonly logger = new Logger(CrmSyncService.name);

  constructor(
    private readonly client: Crm24ClientService,
    private readonly crmConfig: CrmConfigService,
    @InjectRepository(PaymentEntity)
    private readonly paymentsRepo: Repository<PaymentEntity>,
    @InjectRepository(NazrRequestEntity)
    private readonly nazrRequestsRepo: Repository<NazrRequestEntity>,
    @InjectRepository(UserEntity)
    private readonly usersRepo: Repository<UserEntity>,
  ) {}

  /** پس از ثبت نذر: مخاطب + پرداختِ «در انتظار پرداخت» در CRM. */
  async syncNewNazr(nazrId: string): Promise<void> {
    if (!this.crmConfig.enabled) return;
    try {
      const nazr = await this.nazrRequestsRepo.findOne({
        where: { id: nazrId },
        relations: { nazrType: true, payments: true },
      });
      if (!nazr) return;
      if (this.held(nazr.trackingCode)) return;
      const paid = nazr.payments?.filter(p => p.status === 'paid') ?? [];
      if (paid.length > 1) throw new ReviewRequired('چند پرداخت موفق برای یک نذر؛ بررسی مالی لازم است');
      if (paid.length === 1) { await this.syncByPaymentId(paid[0].id); return; }

      await this.withNazrLock(nazr.id, async () => {
        const matches = await this.lookup(nazr.trackingCode);
        if (matches.length > 1) throw new ReviewRequired('چند پرداخت CRM با یک کد پیگیری');
        const remote = matches[0];
        if (remote?.paymentsstatus === PAID) return;
        if (remote && (remote.cf_1764 !== NAZR_SERVICE_NAME || ![PENDING, CANCELLED].includes(remote.paymentsstatus))) {
          throw new ReviewRequired('مغایرت رکورد مالی موجود؛ نیازمند بررسی');
        }
        const amount = this.rialAmount(nazr.amount);
        const status = this.unpaidStatus(nazr);
        if (remote && remote.paymentsstatus === status && Number(remote.amount_currency_value) === amount) return;
        // Updating an existing unpaid request must retain its contact link.
        // Ambiguous profile selection is only needed for a NEW association.
        const contactId = remote
          ? await this.existingRequestContact(nazr, remote)
          : await this.upsertContact(nazr);
        const serviceId = await this.nazrServiceId();

        const fields = {
          relatedcontact: contactId,
          ...(serviceId ? { related_to: serviceId } : {}),
          amount_currency_value: amount,
          paymentsstatus: status,
          paymenttype: 'نذر امام',
          cf_1764: 'نذر امام',
          ...(this.planIntent(nazr) ? { cf_1781: this.planIntent(nazr) } : {}),
          tracking_code: nazr.trackingCode,
          description: nazr.note ?? '',
          assigned_user_id: remote?.assigned_user_id ?? this.crmConfig.config!.assignedUserId,
        };
        if (remote) await this.client.update('Payments', { id: remote.id, ...fields });
        else await this.client.create('Payments', fields);
        this.logger.log(`درخواست CRM همگام شد: ${nazr.trackingCode}`);
      });
    } catch (error) {
      this.failure(`syncNewNazr ${nazrId}`, error);
    }
  }

  /** پس از پرداخت موفق: رکورد CRM مرتبط را «پرداخت شده» می‌کند. */
  async syncByPaymentId(paymentId: string): Promise<void> {
    if (!this.crmConfig.enabled) return;
    try {
      const payment = await this.paymentsRepo.findOne({
        where: { id: paymentId },
        relations: { nazrRequest: { nazrType: true } },
      });
      if (!payment?.nazrRequest || payment.status !== 'paid') return;
      const nazr = payment.nazrRequest;
      if (this.held(nazr.trackingCode)) return;
      await this.withNazrLock(nazr.id, async () => {
        const existing = await this.lookup(nazr.trackingCode);
        if (existing.length > 1) throw new ReviewRequired('چند پرداخت CRM با یک کد پیگیری');
        const remote = existing[0];
        if (remote && this.matchesPaid(remote, payment)) return;
        if (remote && (remote.cf_1764 !== NAZR_SERVICE_NAME || ![PENDING, CANCELLED].includes(remote.paymentsstatus))) {
          throw new ReviewRequired('مغایرت رکورد مالی موجود؛ نیازمند بررسی');
        }
        const contactId = await this.upsertContact(nazr);

        // vtiger در update همه‌ی فیلدهای اجباری (از جمله related_to) را دوباره
        // می‌خواهد؛ بنابراین همیشه با مقدار کامل فرستاده می‌شوند.
        const serviceId = await this.nazrServiceId();
        const paidFields = {
          relatedcontact: contactId,
          ...(serviceId ? { related_to: serviceId } : {}),
          amount_currency_value: this.rialAmount(payment.amount),
          paymentsstatus: 'پرداخت شده',
          paymentsmode:
            payment.method === 'card_to_card' ? 'کارت به کارت' : 'پرداخت آنلاین',
          datereceived: this.jalaliDate(payment.updatedAt),
          paymenttype: 'نذر امام',
          cf_1764: 'نذر امام',
          ...(this.planIntent(nazr) ? { cf_1781: this.planIntent(nazr) } : {}),
          tracking_code: nazr.trackingCode,
          description: nazr.note ?? '',
          assigned_user_id: this.crmConfig.config!.assignedUserId,
        };
        if (remote) {
          await this.client.update('Payments', { id: remote.id, ...paidFields });
        } else {
          await this.client.create<CrmIdResponse>('Payments', paidFields);
        }
      });
    } catch (error) {
      this.failure(`syncByPaymentId ${paymentId}`, error);
    }
  }

  /** مخاطب را بر اساس موبایل پیدا یا بساز. */
  private async upsertContact(nazr: ContactIdentity): Promise<string> {
    const mobile = nazr.donorMobile.trim();
    if (!/^09[0-9]{9}$/.test(mobile)) throw new Error('شماره همراه نامعتبر');
    // Concurrent requests for this donor share the lookup/create operation.
    const key = mobile;
    const pending = this.contactLookups.get(key);
    if (pending) {
      await pending;
      return this.findOrCreateContact(nazr, mobile);
    }
    const operation = this.findOrCreateContact(nazr, mobile);
    this.contactLookups.set(key, operation);
    try { return await operation; } finally { this.contactLookups.delete(key); }
  }

  private async lookupContacts(identities: ContactIdentity[]): Promise<CrmContact[]> {
    const conditions = new Set<string>();
    for (const { donorMobile: mobile } of identities) {
      if (!/^09[0-9]{9}$/.test(mobile)) throw new ReviewRequired('شماره همراه نامعتبر');
      for (const digits of ['0123456789', '۰۱۲۳۴۵۶۷۸۹', '٠١٢٣٤٥٦٧٨٩']) {
        const pattern = [...mobile.slice(1)].map(d => digits[Number(d)]).join('%');
        conditions.add(`mobile LIKE '%${pattern}%'`);
      }
    }
    return this.client.query<CrmContact>(
      `SELECT id,mobile,firstname,lastname,cf_1756,assigned_user_id FROM Contacts WHERE ${[...conditions].join(' OR ')} LIMIT 100;`,
    );
  }

  private normalizedMobile(value: string): string {
    const digits = value.replace(/[۰-۹]/g, d => String('۰۱۲۳۴۵۶۷۸۹'.indexOf(d)))
      .replace(/[٠-٩]/g, d => String('٠١٢٣٤٥٦٧٨٩'.indexOf(d))).replace(/[^0-9]/g, '');
    if (digits.startsWith('0098')) return '0' + digits.slice(4);
    if (digits.startsWith('98')) return '0' + digits.slice(2);
    if (digits.length === 10 && digits.startsWith('9')) return '0' + digits;
    return digits;
  }

  private selectContact(nazr: ContactIdentity, rows: CrmContact[]): CrmContact | undefined {
    const matches = rows.filter(row => this.normalizedMobile(row.mobile) === nazr.donorMobile.trim());
    if (matches.length === 1) return matches[0];
    if (matches.length > 1) {
      const normalize = (name: string) => name.normalize('NFKC').replace(/[يى]/g, 'ی')
        .replace(/ك/g, 'ک').replace(/[\s\u200c\u200d]+/g, '');
      const fullName = normalize(nazr.donorFullName);
      const named = matches.filter(row => normalize((row.firstname || '') + (row.lastname || '')) === fullName);
      if (fullName && named.length === 1) return named[0];
      // Duplicate records for the same full name and mobile: prefer the
      // contact CRM explicitly designates for Nazr, only when unique.
      const nazrProfiles = named.filter(row => row.cf_1756 === 'بله');
      if (fullName && nazrProfiles.length === 1) return nazrProfiles[0];
      throw new ReviewRequired('چند مخاطب با شماره یکسان؛ بررسی دستی هویت لازم است');
    }
    return undefined;
  }

  private async findOrCreateContact(nazr: ContactIdentity, mobile: string): Promise<string> {
    const rows = await this.lookupContacts([{ ...nazr, donorMobile: mobile }]);
    if (rows.length >= 100) throw new ReviewRequired('تعداد مخاطبان برای انتخاب امن بیش از حد است');
    const contact = this.selectContact(nazr, rows);
    if (contact) return this.tagContact(contact);

    const created = await this.client.create<CrmIdResponse>('Contacts', {
      firstname: nazr.donorFirstName ?? '',
      lastname: nazr.donorLastName?.trim() || nazr.donorFullName,
      mobile,
      cf_1570: nazr.donorGender === 'male' ? 'آقا' : nazr.donorGender === 'female' ? 'خانم' : '',
      leadsource: 'سایت نذر امام',
      cf_1756: 'بله',
      assigned_user_id: this.crmConfig.config!.assignedUserId,
    });
    this.logger.log(`مخاطب CRM ساخته شد: ${created.id}`);
    return created.id;
  }

  private async existingRequestContact(nazr: ContactIdentity, remote: CrmPayment): Promise<string> {
    if (!/^\d+x\d+$/.test(remote.relatedcontact)) throw new ReviewRequired('ارجاع مخاطب درخواست معتبر نیست');
    const rows = await this.client.query<CrmContact>(
      `SELECT id,mobile,firstname,lastname,cf_1756,assigned_user_id FROM Contacts WHERE id='${remote.relatedcontact}' LIMIT 1;`,
    );
    const contact = rows[0];
    if (!contact || this.normalizedMobile(contact.mobile) !== nazr.donorMobile.trim()) {
      throw new ReviewRequired('موبایل مخاطب درخواست موجود مغایرت دارد');
    }
    return this.tagContact(contact);
  }

  private async tagContact(contact: CrmContact): Promise<string> {
    if (contact.cf_1756 !== 'بله') {
      await this.client.update('Contacts', {
        id: contact.id, lastname: contact.lastname, mobile: contact.mobile,
        assigned_user_id: contact.assigned_user_id, cf_1756: 'بله',
      });
    }
    return contact.id;
  }

  /** سرویس «نذر امام» (کد حسابداری 1111) را پیدا یا بساز. */
  private async nazrServiceId(): Promise<string | null> {
    const existing = await this.client.query<{ id: string }>(
      `SELECT id FROM Services WHERE servicename='${NAZR_SERVICE_NAME}' LIMIT 1;`,
    );
    if (existing.length > 0) return existing[0].id;

    const created = await this.client.create<CrmIdResponse>('Services', {
      servicename: NAZR_SERVICE_NAME,
      cf_1642: NAZR_SERVICE_CODE,
      description: 'طرح‌های نذر وب‌سایت نذر امام',
      assigned_user_id: this.crmConfig.config!.assignedUserId,
    });
    this.logger.log(`سرویس CRM ساخته شد: ${NAZR_SERVICE_NAME} → ${created.id}`);
    return created.id;
  }

  private planIntent(nazr: NazrRequestEntity): string | null {
    return PLAN_INTENT_BY_SLUG[nazr.nazrType.slug] ?? null;
  }

  /**
   * ارز پایه CRM «ریال» است (نرخ ۱) و کاربران با ارز نمایش «تومان» (نرخ ۰٫۱)
   * می‌بینند؛ پس مقدار باید به ریال ذخیره شود تا نمایشِ تومانی درست باشد.
   */
  private rialAmount(amount: { amount: number; currency: 'IRR' | 'IRT' }): number {
    const rial = amount.currency === 'IRT' ? amount.amount * 10 : amount.amount;
    if (!Number.isSafeInteger(rial) || rial <= 0) throw new ReviewRequired('مبلغ خارج از دقت امن؛ بررسی دستی لازم است');
    return rial;
  }

  /** تاریخ شمسی YYYY-MM-DD برای فیلد تاریخ دریافت در CRM. */
  private jalaliDate(date: Date): string {
    const fmt = new Intl.DateTimeFormat('fa-IR-u-ca-persian', {
      year: 'numeric',
      month: '2-digit',
      day: '2-digit',
      timeZone: 'Asia/Tehran',
    });
    return fmt
      .format(date)
      .replace(/[۰-۹]/g, (digit) => String('۰۱۲۳۴۵۶۷۸۹'.indexOf(digit)));
  }

  private errMessage(error: unknown): string {
    return error instanceof Error ? error.message : String(error);
  }

  private failure(operation: string, error: unknown): void {
    if (error instanceof ReviewRequired) this.logger.warn(`CRM ${operation}: ${this.errMessage(error)}`);
    else {
      this.retryNeeded = true;
      this.logger.error(`CRM ${operation}: ${this.errMessage(error)}`);
    }
  }
}
